package com.taxi.meter.gps

enum class GpsSignal {
    /** Координаты вообще не приходят */
    NONE,

    /** Координаты есть, но слишком грубые или невозможные — не считаем */
    WEAK,

    /** Считаем */
    OK,
}

/**
 * Что происходит с приёмником. Нужен, чтобы отличать выключенную
 * геолокацию от заглушенного сигнала: и то и другое выглядит как
 * замерший счётчик, а чинится по-разному.
 */
data class GpsStatus(
    val signal: GpsSignal = GpsSignal.NONE,
    /** Заявленная погрешность последней точки, м; 0 — неизвестна */
    val accuracyM: Int = 0,
    /** Сколько точек пришло с момента запуска — видно, идёт ли поток вообще */
    val fixCount: Int = 0,
    /** Сколько точек отброшено фильтрами */
    val rejectedCount: Int = 0,
    /** Включена ли геолокация в самом телефоне */
    val locationEnabled: Boolean = true,
    /** Секунд с последней принятой точки; -1 — точек ещё не было */
    val lastFixAgoSec: Int = -1,
)
